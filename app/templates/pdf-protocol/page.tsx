import styles from "./pdf.module.css";
import type { PersonalizedProtocol } from "@/lib/types";

function decodePayload(payload: string | undefined): PersonalizedProtocol | null {
  if (!payload) return null;
  try {
    const normalized = payload.replace(/-/g, "+").replace(/_/g, "/");
    const pad = normalized.length % 4 === 0 ? "" : "=".repeat(4 - (normalized.length % 4));
    const json = Buffer.from(normalized + pad, "base64").toString("utf8");
    return JSON.parse(json) as PersonalizedProtocol;
  } catch {
    return null;
  }
}

function demoProtocol(name: string, goal: string): PersonalizedProtocol {
  return {
    headline: `${name}'s 14-Day Longevity Protocol`,
    summary: `A clean performance plan oriented around ${goal}, with morning activation, midday fueling, and evening recovery.`,
    focusAreas: [
      `Primary goal: ${goal}`,
      "Training load: moderate",
      "Sleep baseline: fair",
      "Stress load: moderate",
    ],
    morning: {
      title: "Morning Activation",
      items: [
        "Outdoor light within 30 minutes of waking",
        "Hydrate before caffeine",
        "Protein-forward breakfast (30–40g)",
        "5-minute mobility for hips and thoracic spine",
      ],
    },
    midday: {
      title: "Midday Performance",
      items: [
        "10–15 minute walk after the largest meal",
        "One protected Zone 2 block",
        "Protein + fiber lunch",
        "One deep-work block with notifications off",
      ],
    },
    evening: {
      title: "Evening Wind-Down",
      items: [
        "Dim lights 60 minutes before bed",
        "Last meal ~3 hours before sleep",
        "Optional magnesium if already tolerated",
        "Write tomorrow’s top 3 priorities",
      ],
    },
    weekly: {
      title: "Weekly Architecture",
      items: [
        "2–3 resistance sessions",
        "1 longer Zone 2 session",
        "1 recovery day with walks only",
        "Sunday protocol review",
      ],
    },
    cautions: [
      "Educational content only — not medical advice.",
      "Introduce one new habit every 3–4 days.",
      "Seek clinical care for chest pain, dizziness, or unexplained fatigue.",
    ],
  };
}

export default async function PdfProtocolPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const params = await searchParams;
  const name = String(params.name ?? "Athlete");
  const goal = String(params.goal ?? "longevity");
  const payload = typeof params.payload === "string" ? params.payload : undefined;
  const protocol = decodePayload(payload) ?? demoProtocol(name, goal);

  return (
    <main className={styles.page}>
      <header className={styles.header}>
        <div>
          <p className={styles.brand}>Kastoria</p>
          <p className={styles.eyebrow}>Longevity Performance Protocol</p>
        </div>
        <p className={styles.date}>
          {new Date().toLocaleDateString("en-GB", {
            day: "2-digit",
            month: "short",
            year: "numeric",
            timeZone: "Europe/Paris",
          })}
        </p>
      </header>

      <section className={styles.hero}>
        <h1>{protocol.headline}</h1>
        <p>{protocol.summary}</p>
      </section>

      <section className={styles.focus}>
        <h2>Focus areas</h2>
        <ul>
          {protocol.focusAreas.map((item) => (
            <li key={item}>{item}</li>
          ))}
        </ul>
      </section>

      <section className={styles.grid}>
        {[protocol.morning, protocol.midday, protocol.evening, protocol.weekly].map(
          (block) => (
            <article key={block.title}>
              <h3>{block.title}</h3>
              <ol>
                {block.items.map((item) => (
                  <li key={item}>{item}</li>
                ))}
              </ol>
            </article>
          ),
        )}
      </section>

      <section className={styles.cautions}>
        <h2>Cautions</h2>
        <ul>
          {protocol.cautions.map((item) => (
            <li key={item}>{item}</li>
          ))}
        </ul>
      </section>

      <footer className={styles.footer}>
        Generated by the Kastoria Longevity Performance Engine
      </footer>
    </main>
  );
}
